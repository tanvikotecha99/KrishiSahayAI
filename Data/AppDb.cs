        // =========================================================
        // DELETE FARM
        // Deletes the farm and all data belonging to it.
        // UserId check prevents deleting another user's farm.
        // =========================================================

        public bool DeleteFarm(
            int farmId,
            string userId)
        {
            using var connection =
                CreateConnection();

            connection.Open();

            using var transaction =
                connection.BeginTransaction();

            try
            {
                // -------------------------------------------------
                // FIRST VERIFY THAT THIS FARM BELONGS TO THE USER
                // -------------------------------------------------

                using (var checkCommand =
                    connection.CreateCommand())
                {
                    checkCommand.Transaction = transaction;

                    checkCommand.CommandText = @"
SELECT COUNT(*)
FROM FarmProfiles
WHERE Id = @FarmId
AND UserId = @UserId;
";

                    AddParameter(checkCommand,
                        "@FarmId",
                        farmId);

                    AddParameter(checkCommand,
                        "@UserId",
                        userId);

                    var exists =
                        Convert.ToInt32(
                            checkCommand.ExecuteScalar());

                    if (exists == 0)
                    {
                        transaction.Rollback();

                        return false;
                    }
                }


                // -------------------------------------------------
                // DELETE FARM CROPS
                // -------------------------------------------------

                using (var command =
                    connection.CreateCommand())
                {
                    command.Transaction = transaction;

                    command.CommandText = @"
DELETE FROM FarmCrops
WHERE FarmId = @FarmId
AND UserId = @UserId;
";

                    AddParameter(command,
                        "@FarmId",
                        farmId);

                    AddParameter(command,
                        "@UserId",
                        userId);

                    command.ExecuteNonQuery();
                }


                // -------------------------------------------------
                // DELETE FARM ACTIVITIES
                // -------------------------------------------------

                using (var command =
                    connection.CreateCommand())
                {
                    command.Transaction = transaction;

                    command.CommandText = @"
DELETE FROM FarmActivities
WHERE FarmProfileId = @FarmId;
";

                    AddParameter(command,
                        "@FarmId",
                        farmId);

                    command.ExecuteNonQuery();
                }


                // -------------------------------------------------
                // DELETE LEARNING PROGRESS
                // -------------------------------------------------

                using (var command =
                    connection.CreateCommand())
                {
                    command.Transaction = transaction;

                    command.CommandText = @"
DELETE FROM LearningLessonCompletions
WHERE FarmProfileId = @FarmId;
";

                    AddParameter(command,
                        "@FarmId",
                        farmId);

                    command.ExecuteNonQuery();
                }


                // -------------------------------------------------
                // DELETE CROP OBSERVATIONS
                // -------------------------------------------------

                using (var command =
                    connection.CreateCommand())
                {
                    command.Transaction = transaction;

                    command.CommandText = @"
DELETE FROM CropObservations
WHERE FarmProfileId = @FarmId;
";

                    AddParameter(command,
                        "@FarmId",
                        farmId);

                    command.ExecuteNonQuery();
                }


                // -------------------------------------------------
                // DELETE SOIL ASSESSMENTS
                // -------------------------------------------------

                using (var command =
                    connection.CreateCommand())
                {
                    command.Transaction = transaction;

                    command.CommandText = @"
DELETE FROM SoilAssessments
WHERE FarmProfileId = @FarmId;
";

                    AddParameter(command,
                        "@FarmId",
                        farmId);

                    command.ExecuteNonQuery();
                }


                // -------------------------------------------------
                // DELETE WATER ASSESSMENTS
                // -------------------------------------------------

                using (var command =
                    connection.CreateCommand())
                {
                    command.Transaction = transaction;

                    command.CommandText = @"
DELETE FROM WaterAssessments
WHERE FarmProfileId = @FarmId;
";

                    AddParameter(command,
                        "@FarmId",
                        farmId);

                    command.ExecuteNonQuery();
                }


                // -------------------------------------------------
                // FINALLY DELETE THE FARM
                // -------------------------------------------------

                int deletedRows;

                using (var command =
                    connection.CreateCommand())
                {
                    command.Transaction = transaction;

                    command.CommandText = @"
DELETE FROM FarmProfiles
WHERE Id = @FarmId
AND UserId = @UserId;
";

                    AddParameter(command,
                        "@FarmId",
                        farmId);

                    AddParameter(command,
                        "@UserId",
                        userId);

                    deletedRows =
                        command.ExecuteNonQuery();
                }


                // -------------------------------------------------
                // COMMIT
                // -------------------------------------------------

                if (deletedRows > 0)
                {
                    transaction.Commit();

                    return true;
                }


                transaction.Rollback();

                return false;
            }
            catch
            {
                transaction.Rollback();

                throw;
            }
        }
