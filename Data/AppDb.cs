        public List<FarmCrop> GetFarmCrops(
    int farmId,
    string userId)
        {
            var crops = new List<FarmCrop>();

            using var connection =
                CreateConnection();

            connection.Open();

            using var command =
                connection.CreateCommand();

            command.CommandText = @"
SELECT *
FROM FarmCrops
WHERE FarmId = @FarmId
AND UserId = @UserId
ORDER BY Id DESC;
";

            AddParameter(command,
                "@FarmId",
                farmId);

            AddParameter(command,
                "@UserId",
                userId);

            using var reader =
                command.ExecuteReader();

            while (reader.Read())
            {
                DateTime? sowingDate = null;

                var sowingDateValue =
                    reader["SowingDate"]?.ToString();

                if (!string.IsNullOrWhiteSpace(
                        sowingDateValue))
                {
                    if (DateTime.TryParse(
                            sowingDateValue,
                            out var parsedDate))
                    {
                        sowingDate = parsedDate;
                    }
                }

                crops.Add(new FarmCrop
                {
                    Id = reader.GetInt32(
                        reader.GetOrdinal("Id")),

                    UserId =
                        reader["UserId"]?.ToString() ?? "",

                    FarmId =
                        Convert.ToInt32(
                            reader["FarmId"]),

                    CropName =
                        reader["CropName"]?.ToString() ?? "",

                    Variety =
                        reader["Variety"]?.ToString() ?? "",

                    Season =
                        reader["Season"]?.ToString() ?? "",

                    Area =
                        Convert.ToDouble(
                            reader["Area"]),

                    AreaUnit =
                        reader["AreaUnit"]?.ToString()
                        ?? "Acre",

                    SowingDate =
                        sowingDate,

                    Notes =
                        reader["Notes"]?.ToString() ?? "",

                    CreatedAt =
                        DateTime.Parse(
                            reader["CreatedAt"]?.ToString()
                            ?? DateTime.UtcNow.ToString("O"))
                });
            }

            return crops;
        }
