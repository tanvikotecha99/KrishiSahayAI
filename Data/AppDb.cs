        private readonly string _connectionString;
        private readonly bool _usePostgres;

        public AppDb(IConfiguration configuration)
        {
            var cloudSqlSocket =
                Environment.GetEnvironmentVariable("INSTANCE_UNIX_SOCKET");

            _usePostgres =
                !string.IsNullOrWhiteSpace(cloudSqlSocket);

            if (_usePostgres)
            {
                var dbUser =
                    Environment.GetEnvironmentVariable("DB_USER");

                var dbPassword =
                    Environment.GetEnvironmentVariable("DB_PASS");

                var dbName =
                    Environment.GetEnvironmentVariable("DB_NAME");

                if (string.IsNullOrWhiteSpace(dbUser) ||
                    string.IsNullOrWhiteSpace(dbPassword) ||
                    string.IsNullOrWhiteSpace(dbName))
                {
                    throw new InvalidOperationException(
                        "Cloud SQL environment variables DB_USER, DB_PASS and DB_NAME are required.");
                }

                _connectionString =
                    $"Host={cloudSqlSocket};" +
                    $"Username={dbUser};" +
                    $"Password={dbPassword};" +
                    $"Database={dbName};" +
                    "Ssl Mode=Disable;" +
                    "Pooling=true;";
            }
            else
            {
                var databasePath =
                    configuration["Database:Path"]
                    ?? "Data/krishisahay.db";

                var directory =
                    Path.GetDirectoryName(databasePath);

                if (!string.IsNullOrWhiteSpace(directory))
                {
                    Directory.CreateDirectory(directory);
                }

                _connectionString =
                    $"Data Source={databasePath}";
            }
        }

        private DbConnection CreateConnection()
        {
            if (_usePostgres)
            {
                return new NpgsqlConnection(_connectionString);
            }

            return new SqliteConnection(_connectionString);
        }

        private static void AddParameter(
            DbCommand command,
            string name,
            object? value)
        {
            var parameter = command.CreateParameter();
            parameter.ParameterName = name;
            parameter.Value = value ?? DBNull.Value;
            command.Parameters.Add(parameter);
        }


