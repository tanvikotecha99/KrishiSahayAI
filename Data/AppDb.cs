        public List<FarmActivity> GetActivities(int farmId)
        {
            var activities =
                new List<FarmActivity>();

            using var connection =
                CreateConnection();

            connection.Open();

            using var command = connection.CreateCommand();

            command.CommandText = @"
SELECT *
FROM FarmActivities
WHERE FarmProfileId = @FarmProfileId
ORDER BY ActivityDate ASC;
";

            AddParameter(command,
                "@FarmProfileId",
                farmId);

            using var reader =
                command.ExecuteReader();

            while (reader.Read())
            {
                activities.Add(new FarmActivity
                {
                    Id = reader.GetInt32(
                        reader.GetOrdinal("Id")),

                    FarmProfileId =
                        reader.GetInt32(
                            reader.GetOrdinal("FarmProfileId")),

                    Title =
                        reader["Title"]?.ToString() ?? "",

                    Description =
                        reader["Description"]?.ToString() ?? "",

                    ActivityDate =
                        DateTime.Parse(
                            reader["ActivityDate"]?.ToString()
                            ?? DateTime.UtcNow.ToString("O")),

                    IsCompleted =
                        Convert.ToInt32(
                            reader["IsCompleted"]) == 1,

                    Category =
                        reader["Category"]?.ToString() ?? ""
                });
            }

            return activities;
        }

